# ── Compiled patterns ───────────────────────────────────────────────────────
_COMPILED_PATTERNS = [re.compile(p, re.IGNORECASE) for p in BLOCKED_NAME_PATTERNS]


def _is_blocked(product: dict[str, Any]) -> bool:
    """Return True if *product* should be excluded from the Individual Test catalog."""
    name_raw: str = product.get("name", "")
    name_lower = name_raw.strip().lower()

    # 1. Always-keep list takes priority over pattern matches
    if name_lower in ALWAYS_KEEP_EXACT_NAMES:
        return False

    # 2. Exact-block list
    if name_lower in BLOCKED_EXACT_NAMES:
        return True

    # 3. Pattern matches
    for pattern in _COMPILED_PATTERNS:
        if pattern.search(name_lower):
            return True

    return False


