# Build the filtered catalog once at import time so all consumers share
# the same reference.
_FILTERED_CATALOG: list[dict[str, Any]] | None = None


def get_catalog() -> list[dict[str, Any]]:
    """Return the filtered list of Individual Test Solutions.

    Results are cached after the first call.  The filter is applied at the
    data layer so no downstream consumer (FAISS index, retriever, LLM prompt)
    can surface blocked products.
    """
    global _FILTERED_CATALOG
    if _FILTERED_CATALOG is None:
        # Deduplicate by entity_id (raw list may have duplicates from scraper)
        seen_ids: set[str] = set()
        unique: list[dict[str, Any]] = []
        for product in _RAW_CATALOG:
            eid = product.get("entity_id", "")
            if eid not in seen_ids:
                seen_ids.add(eid)
                unique.append(product)

        _FILTERED_CATALOG = [p for p in unique if not _is_blocked(p)]

    return _FILTERED_CATALOG


def get_valid_urls() -> set[str]:
    """Return the set of valid catalog URLs (filtered catalog only)."""
    return {p["link"] for p in get_catalog()}


def get_valid_names() -> set[str]:
    """Return the set of valid catalog product names (filtered catalog only)."""
    return {p["name"] for p in get_catalog()}


# Convenience: build a name → product lookup for hallucination recovery
def get_name_to_product() -> dict[str, dict[str, Any]]:
    """Return a mapping of lowercased name → product dict (filtered only)."""
    return {p["name"].lower(): p for p in get_catalog()}


# ---------------------------------------------------------------------------
# Diagnostic helper (not used at runtime)
# ---------------------------------------------------------------------------

def list_blocked_products() -> list[str]:
    """Return names of raw-catalog entries that are filtered out."""
    seen_ids: set[str] = set()
    blocked: list[str] = []
    for product in _RAW_CATALOG:
        eid = product.get("entity_id", "")
        if eid in seen_ids:
            continue
        seen_ids.add(eid)
        if _is_blocked(product):
            blocked.append(product["name"])
    return sorted(blocked)

 # ---------------------------------------------------------------------------

# Filtered catalog accessors

# ---------------------------------------------------------------------------

_FILTERED_CATALOG = [
item for item in _RAW_CATALOG
if not _is_blocked(item)
]

_CATALOG_BY_ID = {
item["entity_id"]: item
for item in _FILTERED_CATALOG
}

def get_catalog():
    """
    Return filtered catalog containing ONLY
    valid Individual Test Solutions.
    """
    return _FILTERED_CATALOG

def get_catalog_by_id(entity_id: str):
    """
    Lookup filtered catalog item by entity_id.
    """
    return _CATALOG_BY_ID.get(str(entity_id))
